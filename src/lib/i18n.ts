export type Language = 'en' | 'ta'
export type TranslationKey = keyof typeof translations.en

export function t(lang: Language, key: string): string {
  const keys = key.split('.')
  let value: any = translations[lang]
  for (const k of keys) {
    value = value?.[k]
  }
  return value || key
}
